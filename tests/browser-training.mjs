import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { chromium } from "../artifacts/browser-tools/node_modules/playwright-core/index.mjs";
import { translations } from "../frontend/src/i18n/translations.ts";
import { require, startServer, useTempDataDir } from "./harness.mjs";

const dataDir = useTempDataDir("training-browser");
const artifactDir = resolve("artifacts/ai/browser");
mkdirSync(artifactDir, { recursive: true });
const socket = {};
require("./src/services/intelligence/runtime.cjs").bindSocket(socket, "conn_default");
require("./src/services/intelligence/chatDirectory.cjs").observe(socket, "400@g.us", "Synthetic classroom");
require("./src/db/db.cjs").checkpoint();
const server = await startServer({ dataDir, routes: true });
const browser = await chromium.launch({ channel: "msedge", headless: true });
const evidence = { date: new Date().toISOString(), browser: browser.version(), data: "disposable synthetic fixtures only", checks: [], pageErrors: [], blockedExternalRequests: [], screenshots: [] };
const check = (name, value) => { assert.ok(value, name); evidence.checks.push({ name, passed: true }); };
let page;
let context;
let currentCheck = "initialization";
const api = async (path) => {
  const response = await context.request.get(`${server.base}/dashboard/api/ai/training${path}`);
  assert.equal(response.status(), 200);
  return response.json();
};
const capture = async (name) => {
  await page.screenshot({ path: resolve(artifactDir, `${name}.png`), fullPage: true });
  evidence.screenshots.push(`${name}.png`);
};
const openContext = async (language, viewport, storageState) => {
  const next = await browser.newContext({ viewport, locale: language, storageState, serviceWorkers: "block" });
  await next.route("**/*", (route) => {
    const url = route.request().url();
    if (new URL(url).origin === server.base) return route.continue();
    evidence.blockedExternalRequests.push(url);
    return route.abort();
  });
  await next.addInitScript((lang) => localStorage.setItem("yuxli_lang", lang), language);
  return next;
};
try {
  context = await openContext("en", { width: 1440, height: 1000 });
  const setup = await context.request.post(`${server.base}/setup`, { form: { password: "browser-synthetic-only", confirm: "browser-synthetic-only" }, headers: { origin: server.base } });
  check("fixture-only setup succeeds", setup.ok());
  page = await context.newPage();
  page.on("pageerror", (error) => evidence.pageErrors.push(error.message));
  page.setDefaultTimeout(12000);
  await page.goto(`${server.base}/#training`);
  const text = translations.en;
  const tab = (key) => page.getByRole("tab", { name: text[key], exact: true });
  const button = (key) => page.getByRole("button", { name: text[key], exact: true });
  await button("trainingAddChat").waitFor();
  currentCheck = "authorized chat setup";
  await button("trainingAddChat").click();
  const dialog = page.getByRole("dialog");
  check("chat picker contains authorized metadata only", await page.locator("#training-chat option").count() === 2);
  await page.getByLabel(text.trainingSelectChat, { exact: true }).selectOption("400@g.us");
  check("new group defaults to Mention Only", await page.locator("#training-response-mode").inputValue() === "mention-only");
  check("new group defaults learning off", !await page.getByLabel(text.trainingEnableLearning, { exact: true }).isChecked());
  check("start requires notice confirmation", await button("trainingStart").isDisabled());
  await page.getByLabel(text.trainingNoticeConfirmation, { exact: true }).check();
  await button("trainingStart").click();
  await dialog.waitFor({ state: "hidden" });
  check("group persists through real API", (await api("/overview")).groups[0].mode === "mention-only");
  check("no invented style score", await page.getByText(text.trainingInsufficientData, { exact: true }).isVisible());
  for (const enabled of [false, true]) {
    const saved = page.waitForResponse((response) => response.url().endsWith("/groups") && response.request().method() === "POST");
    await page.getByRole("switch", { name: text.trainingEnableAi, exact: true }).click();
    check(`automatic AI toggle ${enabled} request succeeds`, (await saved).ok());
    check(`automatic AI toggle ${enabled} persists`, (await api("/overview")).groups[0].enabled === enabled);
  }
  for (const learning of [true, false]) {
    await button("edit").click();
    check("existing group identity cannot be changed", await page.locator("#training-chat").isDisabled());
    await page.getByLabel(text.trainingEnableLearning, { exact: true }).setChecked(learning);
    await page.getByLabel(text.trainingNoticeConfirmation, { exact: true }).check();
    await dialog.getByRole("button", { name: text.save, exact: true }).click();
    await dialog.waitFor({ state: "hidden" });
    check(`learning control ${learning} persists`, (await api("/overview")).groups[0].learning === learning);
  }
  await capture("desktop-automatic");
  currentCheck = "persona create and edit";
  await tab("trainingTab_custom").click();
  await button("trainingCreate").click();
  await page.getByLabel(text.trainingPersonaName, { exact: true }).fill("Browser tutor");
  await page.getByLabel(text.trainingPersonaInstructions, { exact: true }).fill("Use short worked examples.");
  await dialog.getByRole("button", { name: text.save, exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.getByText("Browser tutor", { exact: true }).waitFor();
  check("persona creation persists", (await api("/resources/persona"))[0].name === "Browser tutor");
  await button("edit").click();
  await page.getByLabel(text.trainingPersonaName, { exact: true }).fill("Edited browser tutor");
  await dialog.getByRole("button", { name: text.save, exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  check("persona editing persists", (await api("/resources/persona"))[0].name === "Edited browser tutor");
  await button("edit").click();
  await page.getByLabel(text.trainingPersonaName, { exact: true }).focus();
  for (let index = 0; index < 12; index++) {
    await page.keyboard.press("Tab");
    check(`dialog traps keyboard focus ${index + 1}`, await page.evaluate(() => Boolean(document.activeElement?.closest('[role="dialog"]'))));
  }
  await page.keyboard.press("Escape");
  await dialog.waitFor({ state: "hidden" });
  check("dialog returns focus to edit trigger", await button("edit").evaluate((element) => element === document.activeElement));
  currentCheck = "knowledge upload and approval";
  await tab("trainingKnowledge").click();
  await page.getByLabel(text.trainingUpload, { exact: true }).setInputFiles({ name: "classroom.md", mimeType: "text/markdown", buffer: Buffer.from("The synthetic classroom practice quiz covers linked lists.") });
  await button("save").click();
  await button("trainingApprove").waitFor();
  check("document starts unapproved", !(await api("/resources/document"))[0].approved);
  await button("trainingApprove").click();
  await button("trainingApproved").waitFor();
  check("document approval persists", (await api("/resources/document"))[0].approved);
  currentCheck = "memory confirmation and deletion";
  await tab("trainingMemory").click();
  await page.getByLabel(text.trainingContent, { exact: true }).fill("Use short examples in this workspace.");
  check("memory requires confirmation", await button("save").isDisabled());
  await page.getByLabel(text.trainingMemoryConfirm, { exact: true }).check();
  await button("save").click();
  await button("delete").waitFor();
  check("confirmed memory persisted", (await api("/memory")).length === 1);
  await button("delete").click();
  await page.waitForFunction(() => !document.querySelector('button[aria-label="Delete"]'));
  check("memory deletion persists", (await api("/memory")).length === 0);
  currentCheck = "playground silence and reactions";
  await tab("trainingTab_playground").click();
  await page.getByLabel(text.trainingMessage, { exact: true }).fill("Kal match ka kya scene?");
  await page.getByLabel(text.trainingMentioned, { exact: true }).uncheck();
  await button("trainingTestDecision").click();
  await page.getByText("NO_ACTION", { exact: true }).waitFor();
  check("uninvited playground discussion remains silent", true);
  await page.getByLabel(text.trainingMessage, { exact: true }).fill("Thanks");
  await page.getByLabel(text.trainingReplyToBot, { exact: true }).check();
  await button("trainingTestDecision").click();
  await page.getByText("REACT_ONLY", { exact: true }).waitFor();
  check("playground chooses native reaction without delivery", true);
  currentCheck = "evaluation and version activation";
  await tab("trainingTab_quality").click();
  await button("trainingRunEvaluation").click();
  await button("export").waitFor();
  check("evaluation stored by real backend", (await api("/resources/evaluation")).length === 1);
  await tab("trainingTab_custom").click();
  await tab("trainingResource_version").click();
  await button("trainingSnapshot").click();
  await button("export").waitFor();
  const version = (await api("/resources/version"))[0];
  await tab("trainingAdvanced").click();
  const deployment = JSON.parse(await page.getByLabel(text.trainingConfigurationJson, { exact: true }).inputValue());
  await page.getByLabel(text.trainingConfigurationJson, { exact: true }).fill(JSON.stringify({ ...deployment, enabled: true, versionId: version.id }, null, 2));
  const activation = page.waitForResponse((response) => response.url().endsWith("/deployment") && response.request().method() === "PUT");
  await button("save").click();
  check("version activation request succeeds", (await activation).ok());
  check("explicit version activation persists", (await api("/overview")).deployment.versionId === version.id);
  currentCheck = "subscription enforcement";
  await tab("trainingResource_persona").click();
  const second = await context.request.post(`${server.base}/dashboard/api/ai/training/resources/persona`, { data: { name: "Second synthetic persona", template: "general" }, headers: { origin: server.base } });
  check("free plan allows second custom persona", second.ok());
  await button("trainingCreate").click();
  await page.getByLabel(text.trainingPersonaName, { exact: true }).fill("Over quota persona");
  await dialog.getByRole("button", { name: text.save, exact: true }).click();
  await dialog.getByRole("alert").waitFor();
  check("subscription rejection displayed without closing draft", (await api("/resources/persona")).length === 2);
  await page.keyboard.press("Escape");
  currentCheck = "mobile and Arabic keyboard layouts";
  const storageState = await context.storageState();
  for (const [language, width] of [["en", 390], ["ar", 390], ["ar", 1440]]) {
    const localeContext = await openContext(language, { width, height: 844 }, storageState);
    page = await localeContext.newPage();
    page.on("pageerror", (error) => evidence.pageErrors.push(error.message));
    await page.goto(`${server.base}/#training`);
    const locale = translations[language];
    await page.getByRole("button", { name: locale.trainingAddChat, exact: true }).waitFor();
    check(`${language} ${width}px document direction`, await page.locator("html").getAttribute("dir") === (language === "ar" ? "rtl" : "ltr"));
    check(`${language} ${width}px no page overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    const activeTab = page.getByRole("tab", { name: locale.trainingTab_automatic, exact: true });
    await activeTab.focus();
    await page.keyboard.press(language === "ar" ? "ArrowLeft" : "ArrowRight");
    check(`${language} ${width}px tab arrow navigation`, await page.getByRole("tab", { name: locale.trainingTab_custom, exact: true }).getAttribute("aria-selected") === "true");
    await page.getByRole("button", { name: locale.trainingCreate, exact: true }).waitFor();
    await capture(`${language}-${width}-custom`);
    await localeContext.close();
  }
  check("no browser JavaScript exceptions", evidence.pageErrors.length === 0);
  check("no external runtime dependencies requested", evidence.blockedExternalRequests.length === 0);
  evidence.result = "PASS";
} catch (error) {
  evidence.result = "FAIL";
  evidence.failure = { phase: currentCheck, message: error.stack };
  if (page && !page.isClosed()) await capture("failure").catch(() => {});
  console.error(error);
  process.exitCode = 1;
} finally {
  await browser.close();
  server.stop();
  writeFileSync(resolve(artifactDir, "results.json"), JSON.stringify(evidence, null, 2));
  console.log(JSON.stringify(evidence, null, 2));
}

// Pure Node.js zero-dependency PDF 1.4 generator
// Generates clean, standard-compliant, multi-page PDFs without any external npm packages!
// Safe for Render, Docker, Linux, Windows, anywhere.

function escapePdfText(str) {
  if (!str) return "";
  return str
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)")
    .replace(/[\r\n]+/g, " ");
}

/**
 * Approximate character width table for standard Helvetica
 */
function getCharWidth(char, isBold = false) {
  const code = char.charCodeAt(0);
  if (code < 32 || code > 126) return 0.6; // fallback for ascii
  if ("ijl|.,:;'! ".includes(char)) return 0.28;
  if ("frtI[]()".includes(char)) return 0.35;
  if ("abcdeghknopquvxyz".includes(char)) return 0.55;
  if ("mwMWQ@".includes(char)) return 0.85;
  if (char >= "A" && char <= "Z") return 0.68;
  return 0.55 * (isBold ? 1.1 : 1.0);
}

function measureTextWidth(text, fontSize, isBold = false) {
  let w = 0;
  for (let i = 0; i < text.length; i++) {
    w += getCharWidth(text[i], isBold) * fontSize;
  }
  return w;
}

function wrapLines(text, maxWidth, fontSize, isBold = false) {
  const words = text.split(/\s+/);
  const lines = [];
  let currentLine = "";

  for (const word of words) {
    if (!word) continue;
    const testLine = currentLine ? `${currentLine} ${word}` : word;
    const testWidth = measureTextWidth(testLine, fontSize, isBold);

    if (testWidth <= maxWidth) {
      currentLine = testLine;
    } else {
      if (currentLine) lines.push(currentLine);
      currentLine = word;
    }
  }

  if (currentLine) lines.push(currentLine);
  return lines.length > 0 ? lines : [""];
}

/**
 * Creates a clean formatted PDF Buffer from structured text or markdown-style notes.
 *
 * @param {Object} options
 * @param {string} options.title Document Title
 * @param {string} [options.subtitle] Optional Subtitle / Date / Author
 * @param {string} options.content Main body text (can have # headings, * bullets, etc.)
 * @param {string} [options.footer] Footer text (defaults to "Yuxli Student Notes")
 * @returns {Buffer} Valid PDF 1.4 Buffer
 */
function createDocumentPdf({ title = "Study Notes", subtitle = "", content = "", footer = "Generated by Yuxli Bot" }) {
  // A4 dimensions in points (72 points/inch)
  const pageWidth = 595.28;
  const pageHeight = 841.89;
  const margin = 50;
  const contentWidth = pageWidth - margin * 2;
  const contentHeight = pageHeight - margin * 2;

  // Layout parsing
  const rawLines = content.split("\n");
  const parsedItems = [];

  for (const raw of rawLines) {
    const trimmed = raw.trim();
    if (!trimmed) {
      parsedItems.push({ type: "spacer", height: 10 });
      continue;
    }

    if (trimmed.startsWith("### ")) {
      parsedItems.push({ type: "h3", text: trimmed.slice(4), fontSize: 12, bold: true });
    } else if (trimmed.startsWith("## ")) {
      parsedItems.push({ type: "h2", text: trimmed.slice(3), fontSize: 14, bold: true });
    } else if (trimmed.startsWith("# ")) {
      parsedItems.push({ type: "h1", text: trimmed.slice(2), fontSize: 16, bold: true });
    } else if (trimmed.startsWith("* ") || trimmed.startsWith("- ") || trimmed.startsWith("• ")) {
      const bulletText = trimmed.replace(/^[\*\-•]\s*/, "");
      parsedItems.push({ type: "bullet", text: bulletText, fontSize: 10, bold: false });
    } else if (/^\d+\.\s+/.test(trimmed)) {
      const match = trimmed.match(/^(\d+\.)\s+(.*)/);
      parsedItems.push({ type: "numbered", num: match[1], text: match[2], fontSize: 10, bold: false });
    } else {
      parsedItems.push({ type: "p", text: trimmed, fontSize: 10, bold: false });
    }
  }

  // Break items into printable lines and paginate
  const pages = [];
  let currentPageOperations = [];
  let currentY = pageHeight - margin;

  function checkPageBreak(neededHeight) {
    if (currentY - neededHeight < margin + 30) {
      pages.push(currentPageOperations);
      currentPageOperations = [];
      currentY = pageHeight - margin - 30; // space after top margin on subsequent pages
    }
  }

  // Draw Header on first page
  // Title
  const titleLines = wrapLines(title, contentWidth, 18, true);
  for (const tLine of titleLines) {
    currentPageOperations.push({
      font: "/F2",
      size: 18,
      x: margin,
      y: currentY - 18,
      text: tLine,
      color: "0.1 0.1 0.2",
    });
    currentY -= 24;
  }

  // Subtitle
  if (subtitle) {
    currentPageOperations.push({
      font: "/F1",
      size: 10,
      x: margin,
      y: currentY - 10,
      text: subtitle,
      color: "0.4 0.4 0.5",
    });
    currentY -= 16;
  }

  // Horizontal divider rule
  currentPageOperations.push({
    type: "line",
    x1: margin,
    y1: currentY - 5,
    x2: pageWidth - margin,
    y2: currentY - 5,
    lineWidth: 1,
    color: "0.8 0.8 0.85",
  });
  currentY -= 20;

  // Process items
  for (const item of parsedItems) {
    if (item.type === "spacer") {
      currentY -= item.height;
      continue;
    }

    if (item.type === "h1" || item.type === "h2" || item.type === "h3") {
      const font = "/F2";
      const size = item.fontSize;
      const spacingBefore = item.type === "h1" ? 18 : item.type === "h2" ? 14 : 10;
      const spacingAfter = size + 6;

      checkPageBreak(spacingBefore + spacingAfter);
      currentY -= spacingBefore;

      const lines = wrapLines(item.text, contentWidth, size, true);
      for (const line of lines) {
        checkPageBreak(size + 4);
        currentPageOperations.push({
          font,
          size,
          x: margin,
          y: currentY - size,
          text: line,
          color: item.type === "h1" ? "0.1 0.2 0.4" : "0.2 0.3 0.4",
        });
        currentY -= size + 5;
      }
      currentY -= 4;
      continue;
    }

    if (item.type === "bullet") {
      const size = item.fontSize;
      const bulletIndent = 16;
      const lines = wrapLines(item.text, contentWidth - bulletIndent, size, false);

      checkPageBreak((lines.length * (size + 4)) + 4);

      // Bullet symbol
      currentPageOperations.push({
        font: "/F2",
        size,
        x: margin + 4,
        y: currentY - size,
        text: "•",
        color: "0.25 0.35 0.7",
      });

      for (let i = 0; i < lines.length; i++) {
        currentPageOperations.push({
          font: "/F1",
          size,
          x: margin + bulletIndent,
          y: currentY - size,
          text: lines[i],
          color: "0.15 0.15 0.15",
        });
        currentY -= size + 4;
      }
      currentY -= 2;
      continue;
    }

    if (item.type === "numbered") {
      const size = item.fontSize;
      const numIndent = 20;
      const lines = wrapLines(item.text, contentWidth - numIndent, size, false);

      checkPageBreak((lines.length * (size + 4)) + 4);

      currentPageOperations.push({
        font: "/F2",
        size,
        x: margin,
        y: currentY - size,
        text: item.num,
        color: "0.2 0.3 0.6",
      });

      for (let i = 0; i < lines.length; i++) {
        currentPageOperations.push({
          font: "/F1",
          size,
          x: margin + numIndent,
          y: currentY - size,
          text: lines[i],
          color: "0.15 0.15 0.15",
        });
        currentY -= size + 4;
      }
      currentY -= 2;
      continue;
    }

    // Paragraph
    const size = item.fontSize;
    const lines = wrapLines(item.text, contentWidth, size, false);
    for (const line of lines) {
      checkPageBreak(size + 4);
      currentPageOperations.push({
        font: "/F1",
        size,
        x: margin,
        y: currentY - size,
        text: line,
        color: "0.15 0.15 0.15",
      });
      currentY -= size + 4;
    }
    currentY -= 3;
  }

  // Push last page
  if (currentPageOperations.length > 0 || pages.length === 0) {
    pages.push(currentPageOperations);
  }

  const totalPages = pages.length;

  // Build PDF Objects
  const pdfObjects = [];
  function addObject(contentStr) {
    pdfObjects.push(contentStr);
    return pdfObjects.length; // 1-indexed object id
  }

  // Obj 1: Catalog (will point to Obj 2 Pages)
  // Obj 2: Pages container
  // Obj 3: Font F1 (Helvetica)
  // Obj 4: Font F2 (Helvetica-Bold)

  const fontF1Id = 3;
  const fontF2Id = 4;

  const pageObjectIds = [];

  // Placeholder indices
  // We'll calculate object IDs:
  // 1: Catalog
  // 2: Pages
  // 3: F1
  // 4: F2
  // For each page:
  //   PageObj (5 + i*2)
  //   ContentStreamObj (6 + i*2)

  let nextObjId = 5;
  const pageStreamPairs = [];

  for (let i = 0; i < totalPages; i++) {
    const pageId = nextObjId++;
    const streamId = nextObjId++;
    pageObjectIds.push(pageId);
    pageStreamPairs.push({ pageId, streamId, ops: pages[i], pageNum: i + 1 });
  }

  const catalogObj = `1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj`;
  const pagesObj = `2 0 obj\n<< /Type /Pages /Kids [${pageObjectIds.map((id) => `${id} 0 R`).join(" ")}] /Count ${totalPages} >>\nendobj`;
  const f1Obj = `3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>\nendobj`;
  const f2Obj = `4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>\nendobj`;

  const assembledObjects = [catalogObj, pagesObj, f1Obj, f2Obj];

  for (const pair of pageStreamPairs) {
    // Generate page content stream
    let streamOps = "";

    // Draw content operations
    for (const op of pair.ops) {
      if (op.type === "line") {
        streamOps += `q\n${op.color} RG\n${op.lineWidth} w\n${op.x1} ${op.y1} m\n${op.x2} ${op.y2} l\nS\nQ\n`;
      } else {
        const escaped = escapePdfText(op.text);
        streamOps += `q\n${op.color || "0 0 0"} rg\nBT\n${op.font} ${op.size} Tf\n${op.x} ${op.y} Td\n(${escaped}) Tj\nET\nQ\n`;
      }
    }

    // Add footer and page number
    const footerText = `${footer}  •  Page ${pair.pageNum} of ${totalPages}`;
    const escapedFooter = escapePdfText(footerText);
    streamOps += `q\n0.5 0.5 0.55 rg\nBT\n/F1 8 Tf\n${margin} ${margin - 15} Td\n(${escapedFooter}) Tj\nET\nQ\n`;

    // Add subtle footer divider line
    streamOps += `q\n0.85 0.85 0.88 RG\n0.5 w\n${margin} ${margin - 5} m\n${pageWidth - margin} ${margin - 5} l\nS\nQ\n`;

    const streamLen = Buffer.byteLength(streamOps, "utf-8");

    const pageObjStr = `${pair.pageId} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Contents ${pair.streamId} 0 R /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> >>\nendobj`;
    const streamObjStr = `${pair.streamId} 0 obj\n<< /Length ${streamLen} >>\nstream\n${streamOps}\nendstream\nendobj`;

    assembledObjects.push(pageObjStr);
    assembledObjects.push(streamObjStr);
  }

  // Build the complete file with xref table
  let pdfOutput = "%PDF-1.4\n";
  const offsets = [];

  for (let i = 0; i < assembledObjects.length; i++) {
    offsets.push(Buffer.byteLength(pdfOutput, "utf-8"));
    pdfOutput += `${assembledObjects[i]}\n`;
  }

  const xrefOffset = Buffer.byteLength(pdfOutput, "utf-8");
  const totalObjCount = assembledObjects.length + 1; // including 0 0 obj

  pdfOutput += `xref\n0 ${totalObjCount}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    pdfOutput += `${String(offset).padStart(10, "0")} 00000 n \n`;
  }

  pdfOutput += `trailer\n<< /Size ${totalObjCount} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return Buffer.from(pdfOutput, "utf-8");
}

module.exports = {
  createDocumentPdf,
};
